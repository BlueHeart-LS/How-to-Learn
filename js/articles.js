function getSavedArticles() {
  try {
    return JSON.parse(localStorage.getItem("howToLearnArticles") || "{}");
  } catch {
    return {};
  }
}

let serverArticles = {};
let serverArticleViews = {};
const reportedArticleViews = new Set();
const savedArticleViewsKey = "howToLearnArticleViews";

function canUseArticleApi() {
  return window.location.protocol === "http:" || window.location.protocol === "https:";
}

function getSupabaseClient() {
  return window.HowToLearnSupabase?.isConfigured ? window.HowToLearnSupabase.client : null;
}

function getSavedArticleViews() {
  try {
    return JSON.parse(localStorage.getItem(savedArticleViewsKey) || "{}");
  } catch {
    return {};
  }
}

function writeSavedArticleViews(views) {
  localStorage.setItem(savedArticleViewsKey, JSON.stringify(views));
}

function getArticleView(slug, article = {}) {
  const savedViews = getSavedArticleViews();
  return Math.max(
    0,
    Number(serverArticleViews[slug]) || 0,
    Number(savedViews[slug]) || 0,
    Number(article.views) || 0,
  );
}

function setArticleView(slug, views, options = {}) {
  const nextViews = Math.max(0, Number(views) || 0);
  serverArticleViews[slug] = nextViews;
  if (serverArticles[slug]) {
    serverArticles[slug] = { ...serverArticles[slug], views: String(nextViews) };
  }

  if (options.persistLocal !== false) {
    const savedViews = getSavedArticleViews();
    savedViews[slug] = Math.max(Number(savedViews[slug]) || 0, nextViews);
    writeSavedArticleViews(savedViews);
  }
}

function mapSupabaseArticle(row) {
  return {
    title: row.title,
    category: row.category,
    author: row.author,
    date: row.published_date || "",
    views: String(row.views || 0),
    coverClass: row.cover_class || "people",
    coverImage: row.cover_image || "",
    tags: row.tags || [],
    excerpt: row.excerpt || "",
    body: row.body || [],
  };
}

async function loadServerArticles() {
  const supabase = getSupabaseClient();
  if (supabase) {
    try {
      const [{ data: articles, error: articlesError }, { data: views, error: viewsError }] = await Promise.all([
        supabase.from("articles").select("*").order("updated_at", { ascending: false }),
        supabase.from("article_views").select("slug,views"),
      ]);
      if (articlesError) throw articlesError;
      if (viewsError) throw viewsError;

      serverArticles = Object.fromEntries((articles || []).map((row) => [row.slug, mapSupabaseArticle(row)]));
      serverArticleViews = Object.fromEntries((views || []).map((row) => [row.slug, row.views]));
      window.dispatchEvent(new CustomEvent("howtolearn:articles-ready"));
      return serverArticles;
    } catch (error) {
      console.warn("Unable to load Supabase articles or views.", error);
      serverArticles = {};
      serverArticleViews = {};
      return {};
    }
  }

  if (!canUseArticleApi()) return {};

  try {
    const [articlesResponse, viewsResponse] = await Promise.all([
      fetch("/api/articles", { cache: "no-store" }),
      fetch("/api/article-views", { cache: "no-store" }),
    ]);
    if (!articlesResponse.ok) throw new Error("Article API unavailable");
    serverArticles = await articlesResponse.json();
    serverArticleViews = viewsResponse.ok ? await viewsResponse.json() : {};
    window.dispatchEvent(new CustomEvent("howtolearn:articles-ready"));
    return serverArticles;
  } catch {
    serverArticles = {};
    return {};
  }
}

function getArticleLibrary() {
  const articles = { ...defaultArticles, ...getSavedArticles(), ...serverArticles };
  Object.entries(articles).forEach(([slug, article]) => {
    articles[slug] = { ...article, views: String(getArticleView(slug, article)) };
  });
  return articles;
}

function getArticleList() {
  return Object.entries(getArticleLibrary()).map(([slug, article]) => ({ slug, ...article }));
}

function applyArticleCover(element, article, baseClass) {
  element.className = `${baseClass} ${article.coverImage ? "has-image" : article.coverClass || "people"}`;
  if (article.coverImage) {
    const isAbsolute = /^https?:\/\//.test(article.coverImage);
    const prefix = !isAbsolute && window.location.pathname.includes("/pages/") ? "../" : "";
    element.style.backgroundImage = `url("${prefix}${article.coverImage}")`;
  } else {
    element.style.backgroundImage = "";
  }
}

function renderArticlePage() {
  const title = document.querySelector("[data-article-title]");
  if (!title) return;

  const articles = getArticleLibrary();
  const params = new URLSearchParams(window.location.search);
  const slug = params.get("slug") || "feynman";
  const article = articles[slug] || articles.feynman;

  document.title = `${article.title}｜如何學 How to Learn`;
  title.textContent = article.title;
  document.querySelector("[data-article-category]").textContent = article.category || "學習方法";
  document.querySelector("[data-article-author]").textContent = article.author || "如何學編輯部";
  document.querySelector("[data-article-date]").textContent = article.date || "";
  document.querySelector("[data-article-views]").textContent = article.views || "0";

  const cover = document.querySelector("[data-article-cover]");
  applyArticleCover(cover, article, "article-cover");

  const body = document.querySelector("[data-article-body]");
  body.replaceChildren();
  (article.body || []).forEach((paragraph) => {
    const p = document.createElement("p");
    p.textContent = paragraph;
    body.appendChild(p);
  });

  const tags = document.querySelector("[data-article-tags]");
  tags.replaceChildren();
  (article.tags || []).forEach((tag) => {
    const span = document.createElement("span");
    span.textContent = tag;
    tags.appendChild(span);
  });
}

async function reportArticleView(slug) {
  if (!canUseArticleApi() || reportedArticleViews.has(slug)) return;
  reportedArticleViews.add(slug);

  const currentArticle = getArticleLibrary()[slug];
  const optimisticViews = getArticleView(slug, currentArticle) + 1;
  setArticleView(slug, optimisticViews);
  const views = document.querySelector("[data-article-views]");
  if (views) {
    views.textContent = String(optimisticViews);
  }
  window.dispatchEvent(new CustomEvent("howtolearn:articles-ready"));

  try {
    const supabase = getSupabaseClient();
    let payload;
    if (supabase) {
      const { data, error } = await supabase.rpc("increment_article_view", { article_slug: slug });
      if (error) throw error;
      payload = { slug, views: data };
    } else {
      const response = await fetch(`/api/articles/${encodeURIComponent(slug)}/view`, { method: "POST" });
      if (!response.ok) throw new Error("Article view API unavailable");
      payload = await response.json();
    }
    const syncedViews = Math.max(getArticleView(payload.slug), Number(payload.views) || 0);
    setArticleView(payload.slug, syncedViews);
    if (views && payload.slug === slug) {
      views.textContent = String(syncedViews);
    }
    window.dispatchEvent(new CustomEvent("howtolearn:articles-ready"));
  } catch (error) {
    console.warn("Unable to sync article view count.", error);
    // View tracking is non-critical; keep the article readable if the API is unavailable.
  }
}

window.HowToLearnArticles = {
  defaultArticles,
  getArticleLibrary,
  getArticleList,
  loadServerArticles
};

window.HowToLearnArticleCovers = {
  applyArticleCover
};

renderArticlePage();
loadServerArticles().then(() => {
  renderArticlePage();
  const title = document.querySelector("[data-article-title]");
  if (!title) return;
  const params = new URLSearchParams(window.location.search);
  reportArticleView(params.get("slug") || "feynman");
});
